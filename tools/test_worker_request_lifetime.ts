import assert from 'node:assert/strict';
import { createWorkerRequestLifetime } from '../web/src/services/personalized/workerRequestLifetime.ts';
const lifetime = createWorkerRequestLifetime();
assert.equal(await lifetime.run(async () => 42), 42);
await assert.rejects(lifetime.run(async () => { throw new Error('inference failed'); }), /inference failed/);
await assert.rejects(lifetime.run(() => { throw new Error('transfer failed'); }), /transfer failed/);
let release!: (v: number) => void;
const pending = lifetime.run(() => new Promise<number>(resolve => { release = resolve; }));
let active = true;
const tracked = pending.finally(() => { active = false; });
const rejection = assert.rejects(tracked, /source replaced/);
lifetime.close(new Error('source replaced'));
await rejection;
assert.equal(active, false, 'terminated RPC must release active analysis without a Worker response');
release(99);
let started = false;
await assert.rejects(lifetime.run(async () => { started = true; }), /source replaced/);
assert.equal(started, false);
lifetime.close(new Error('second close'));
const next = createWorkerRequestLifetime();
assert.equal(await next.run(async () => 7), 7, 'next photo uses an independent lifetime');
console.log('worker request lifetime: completion, errors and cancellation passed');
