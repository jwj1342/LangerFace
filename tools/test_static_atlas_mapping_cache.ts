import assert from 'node:assert/strict';
import fs from 'node:fs';
import { mapAtlas } from '../web/src/services/geometryAtlas.ts';
import { createStaticAtlasMappingCache } from '../web/src/services/staticAtlasMappingCache.ts';

const read = (p: string) => JSON.parse(fs.readFileSync(new URL(p, import.meta.url), 'utf8'));
const atlas = read('../web/assets/atlas_rstl.json').lines;
const triangles = read('../web/assets/triangles.json');
const landmarks = read('../web/test/expected.json').frames[0].landmarks;
let calls = 0;
const cache = createStaticAtlasMappingCache((...args) => { calls++; return mapAtlas(...args); });
const options = { expandForehead: true, foreheadBridgeLineCount: 16 };
const expected = mapAtlas(atlas, landmarks, triangles, options);
assert.deepEqual(cache.map(atlas, landmarks, triangles, options), expected);
const copy = cache.map(structuredClone(atlas), structuredClone(landmarks), triangles, options);
assert.equal(calls, 1, 'identical input values reuse computation');
copy[0].pts[0][0] += 100;
assert.deepEqual(cache.map(atlas, landmarks, triangles, options), expected, 'display edits cannot corrupt cached baseline');
landmarks[0][0] += 1;
assert.deepEqual(cache.map(atlas, landmarks, triangles, options), mapAtlas(atlas, landmarks, triangles, options));
assert.equal(calls, 2, 'in-place landmark change invalidates');
atlas[0].points[0][1] += 0.001;
cache.map(atlas, landmarks, triangles, options);
assert.equal(calls, 3, 'in-place atlas change invalidates');
options.foreheadBridgeLineCount = 15;
cache.map(atlas, landmarks, triangles, options);
assert.equal(calls, 4, 'options change invalidates');
triangles[0] = [...triangles[0]].reverse();
cache.map(atlas, landmarks, triangles, options);
assert.equal(calls, 5, 'topology change invalidates');
landmarks[0][0] -= 1;
cache.map(atlas, landmarks, triangles, options);
assert.equal(calls, 6, 'old faces are not retained as history');
cache.clear();
cache.map(atlas, landmarks, triangles, options);
assert.equal(calls, 7);
console.log('static atlas mapping cache: geometry parity and invalidation passed');
